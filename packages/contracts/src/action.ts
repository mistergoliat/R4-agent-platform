import { z } from 'zod';
import type { TaskStatus } from './task.js';
import {
  RISK_CLASSES,
  identityAssuranceSchema,
  trustedActionContextSchema,
  writeRecoveryStrategySchema,
  type CapabilityDefinition,
  type TrustedActionContext,
  type WriteRecoveryStrategy,
} from './capability.js';
import { workerIdSchema } from './lease.js';
import {
  agentIdSchema,
  capabilityIdSchema,
  correlationIdSchema,
  jsonObjectSchema,
  jsonValueSchema,
  positiveIntSchema,
  slugSchema,
  timestampSchema,
  uniqueArray,
  uuidSchema,
  type JsonValue,
} from './primitives.js';

/**
 * Governed execution contracts (R4-D). The path of every effect is
 *
 *   ActionProposal (intent) → PolicyDecision (platform) → ActionCommand
 *   (trusted, keyed) → ActionAttempt* (append-only) → ActionReceipt (evidence)
 *
 * Each record is written by the platform only. The model contributes the
 * proposal's capability id, arguments and evidence references — nothing else.
 * No record here is domain truth: a receipt proves what the platform knows
 * happened at a point in time, not what the resource looks like now.
 */

/** Reason codes: machine-readable, stable, lowercase. */
const codeSchema = z.string().regex(/^[a-z][a-z0-9_.]*$/).max(128);

/**
 * Platform execution key: generated by R4 when the command is created,
 * persisted before any external call and reused by every attempt, replay
 * and reconciliation of that command — never regenerated by a new worker.
 */
export const executionKeySchema = z.string().regex(/^r4x_[0-9a-f]{32}$/, 'must be a platform execution key');
export type ExecutionKey = z.infer<typeof executionKeySchema>;

// ---------------------------------------------------------------------------
// ActionProposal — intent, never execution
// ---------------------------------------------------------------------------

export const actionProposalSchema = z.strictObject({
  proposalId: uuidSchema,
  taskId: uuidSchema,
  runId: uuidSchema,
  /** The run step (iteration) whose decision this is. */
  stepId: uuidSchema,
  iteration: positiveIntSchema,
  agentId: agentIdSchema,
  agentVersion: positiveIntSchema,
  /** As proposed: may name an unknown capability (that is itself evidence). */
  capabilityId: z.string().min(1).max(256),
  /** Untrusted until validated against the capability's input schema. */
  arguments: jsonObjectSchema,
  /** Observations of the task the proposal relies on (verified to exist when recorded). */
  evidenceRefs: uniqueArray(uuidSchema).max(100),
  /** The context the model decided with (null only when recorded without one). */
  contextSnapshotId: uuidSchema.nullable(),
  leaseGeneration: positiveIntSchema,
  correlationId: correlationIdSchema,
  createdAt: timestampSchema,
});
export type ActionProposal = z.infer<typeof actionProposalSchema>;

// ---------------------------------------------------------------------------
// PolicyDecision — deterministic platform authority
// ---------------------------------------------------------------------------

export const POLICY_OUTCOMES = ['allow', 'deny', 'require_approval'] as const;
export const policyOutcomeSchema = z.enum(POLICY_OUTCOMES);
export type PolicyOutcome = z.infer<typeof policyOutcomeSchema>;

/** Which policy produced a decision: explainable after the policy changes. */
export const policyIdentitySchema = z.strictObject({
  policyId: slugSchema,
  version: positiveIntSchema,
  /** sha256 of the canonical policy configuration. */
  hash: z.string().regex(/^[0-9a-f]{64}$/),
  engineVersion: z.string().min(1).max(64),
});
export type PolicyIdentity = z.infer<typeof policyIdentitySchema>;

export const policyDecisionSchema = z.strictObject({
  decisionId: uuidSchema,
  proposalId: uuidSchema,
  taskId: uuidSchema,
  runId: uuidSchema,
  agentId: agentIdSchema,
  agentVersion: positiveIntSchema,
  capabilityId: capabilityIdSchema,
  capabilityVersion: positiveIntSchema,
  riskClass: z.enum(RISK_CLASSES),
  outcome: policyOutcomeSchema,
  reasonCode: codeSchema,
  /** The rule that decided (stable id within the policy). */
  rule: z.string().min(1).max(128),
  message: z.string().max(2000),
  policy: policyIdentitySchema,
  identityAssurance: identityAssuranceSchema,
  leaseGeneration: positiveIntSchema,
  correlationId: correlationIdSchema,
  evaluatedAt: timestampSchema,
});
export type PolicyDecision = z.infer<typeof policyDecisionSchema>;

// ---------------------------------------------------------------------------
// ActionCommand / ActionExecution — what the platform will execute, and how far it got
// ---------------------------------------------------------------------------

/** How the command may be repeated, fixed when it is created (not by whatever code runs recovery). */
export const writeExecutionSemanticsSchema = z.strictObject({
  recovery: writeRecoveryStrategySchema,
  reconcileSupported: z.boolean(),
  /** Bound on execute attempts, and separately on reconcile attempts (capability retry policy). */
  maxAttempts: z.int().min(1).max(10),
  initialBackoffMs: z.int().min(0).max(60_000),
}).refine((s) => s.recovery !== 'reconcile_before_retry' || s.reconcileSupported, {
  message: 'reconcile_before_retry requires a reconcile handler',
  path: ['reconcileSupported'],
});
export type WriteExecutionSemantics = z.infer<typeof writeExecutionSemanticsSchema>;

/** Immutable: created atomically with an ALLOW decision, only from trusted data. */
export const actionCommandSchema = z.strictObject({
  executionId: uuidSchema,
  proposalId: uuidSchema,
  policyDecisionId: uuidSchema,
  taskId: uuidSchema,
  runId: uuidSchema,
  capabilityId: capabilityIdSchema,
  capabilityVersion: positiveIntSchema,
  riskClass: z.enum(RISK_CLASSES).exclude(['READ']),
  executionKey: executionKeySchema,
  semantics: writeExecutionSemanticsSchema,
  validatedArguments: jsonObjectSchema,
  trustedContext: trustedActionContextSchema,
  correlationId: correlationIdSchema,
  createdAt: timestampSchema,
});
export type ActionCommand = z.infer<typeof actionCommandSchema>;

/**
 * Operational lifecycle of a command:
 *
 *   prepared ──► executing ──► succeeded | rejected | failed      (receipt)
 *                    │
 *                    └──────► needs_reconciliation                (outcome unknown)
 *
 * `succeeded/rejected/failed` exist only together with the receipt that
 * proves them. `needs_reconciliation` is set whenever a run ends while an
 * attempt's outcome is unknown; resolving it is out of R4-D's scope.
 */
export const ACTION_EXECUTION_STATUSES = ['prepared', 'executing', 'succeeded', 'rejected', 'failed', 'needs_reconciliation'] as const;
export const actionExecutionStatusSchema = z.enum(ACTION_EXECUTION_STATUSES);
export type ActionExecutionStatus = z.infer<typeof actionExecutionStatusSchema>;
export const RESOLVED_ACTION_EXECUTION_STATUSES = ['succeeded', 'rejected', 'failed'] as const satisfies readonly ActionExecutionStatus[];

export const actionExecutionSchema = actionCommandSchema.extend({
  status: actionExecutionStatusSchema,
  version: positiveIntSchema,
  updatedAt: timestampSchema,
});
export type ActionExecution = z.infer<typeof actionExecutionSchema>;

// ---------------------------------------------------------------------------
// ActionAttempt — one external call, append-only
// ---------------------------------------------------------------------------

/**
 * execute    the first execution of the command
 * replay     a later execution with the SAME key (idempotent replay / transport retry)
 * reconcile  a lookup of the outcome by key
 */
export const ACTION_ATTEMPT_KINDS = ['execute', 'replay', 'reconcile'] as const;
export const actionAttemptKindSchema = z.enum(ACTION_ATTEMPT_KINDS);
export type ActionAttemptKind = z.infer<typeof actionAttemptKindSchema>;

/**
 * applied      the effect happened (now, or earlier under the same key)
 * rejected     the domain refused the command; no effect (e.g. version conflict)
 * failed       the domain reports a definitive failure; no effect
 * not_applied  reconciliation: the domain has no effect for this key
 * unknown      the attempt returned without a knowable outcome
 * (null)       the attempt never reported back (worker died or lost its lease)
 */
export const ACTION_ATTEMPT_OUTCOMES = ['applied', 'rejected', 'failed', 'not_applied', 'unknown'] as const;
export const actionAttemptOutcomeSchema = z.enum(ACTION_ATTEMPT_OUTCOMES);
export type ActionAttemptOutcome = z.infer<typeof actionAttemptOutcomeSchema>;

export const actionAttemptSchema = z
  .strictObject({
    attemptId: uuidSchema,
    executionId: uuidSchema,
    attemptNumber: positiveIntSchema,
    kind: actionAttemptKindSchema,
    workerId: workerIdSchema,
    leaseGeneration: positiveIntSchema,
    startedAt: timestampSchema,
    finishedAt: timestampSchema.nullable(),
    outcome: actionAttemptOutcomeSchema.nullable(),
    errorCode: codeSchema.nullable(),
    /** Structured, bounded detail (codes, refs, flags) — never raw payloads. */
    detail: jsonValueSchema.nullable(),
  })
  .refine((a) => (a.finishedAt === null) === (a.outcome === null), { message: 'an attempt finishes exactly when its outcome is recorded', path: ['finishedAt'] })
  .refine((a) => a.outcome !== 'not_applied' || a.kind === 'reconcile', { message: 'only a reconciliation can establish not_applied', path: ['outcome'] })
  .refine((a) => (a.kind === 'execute') === (a.attemptNumber === 1), { message: 'the first attempt is the execution; later executions are replays', path: ['kind'] });
export type ActionAttempt = z.infer<typeof actionAttemptSchema>;

// ---------------------------------------------------------------------------
// ActionReceipt — immutable evidence of the known outcome
// ---------------------------------------------------------------------------

export const RECEIPT_STATUSES = ['succeeded', 'rejected', 'failed'] as const;
export const receiptStatusSchema = z.enum(RECEIPT_STATUSES);
export type ReceiptStatus = z.infer<typeof receiptStatusSchema>;

const refSchema = z.string().min(1).max(512);

export const actionReceiptSchema = z
  .strictObject({
    receiptId: uuidSchema,
    executionId: uuidSchema,
    proposalId: uuidSchema,
    taskId: uuidSchema,
    runId: uuidSchema,
    capabilityId: capabilityIdSchema,
    capabilityVersion: positiveIntSchema,
    executionKey: executionKeySchema,
    status: receiptStatusSchema,
    /** Domain reference of the affected resource, when the capability reports one. */
    resourceRef: refSchema.nullable(),
    /** Domain reference of the operation itself, when the capability reports one. */
    externalOperationRef: refSchema.nullable(),
    /** Schema-validated capability output (succeeded only). */
    result: jsonValueSchema.nullable(),
    error: z.strictObject({ code: codeSchema, message: z.string().max(2000), details: jsonValueSchema.nullable() }).nullable(),
    /** When the domain applied the effect (as reported), otherwise when the outcome was established. */
    executedAt: timestampSchema,
    recordedAt: timestampSchema,
    evidence: z.strictObject({
      obtainedVia: actionAttemptKindSchema,
      attemptId: uuidSchema,
      attemptNumber: positiveIntSchema,
      /** Attempts recorded for the command when the outcome was established. */
      attempts: positiveIntSchema,
      /** Whether the domain reported that this call returned an earlier effect (duplicate prevented). */
      replayed: z.boolean(),
    }),
    correlationId: correlationIdSchema,
  })
  .refine((r) => (r.status === 'succeeded') === (r.error === null), { message: 'error is present exactly when the action did not succeed', path: ['error'] })
  .refine((r) => r.status === 'succeeded' || r.result === null, { message: 'only a succeeded receipt carries a result', path: ['result'] });
export type ActionReceipt = z.infer<typeof actionReceiptSchema>;

// ---------------------------------------------------------------------------
// Authorizer port — implemented by the Policy Engine, called by the platform
// ---------------------------------------------------------------------------

/**
 * Everything a policy decision may depend on. Every field comes from the
 * platform: durable task/run/agent records, the registered capability and the
 * command semantics its owner declared. The proposal contributes only which
 * capability it names and which evidence it cites — never arguments, which a
 * policy does not interpret.
 */
export interface PolicyInput {
  /** Runtime-validated, proposal-specific human evidence, never supplied by the model. */
  readonly approval?: { readonly requestId: string; readonly proposalId: string; readonly capabilityId: string; readonly capabilityVersion: number; readonly argumentsMatch: boolean };
  readonly proposal: { readonly proposalId: string; readonly evidenceRefs: readonly string[] };
  readonly agent: { readonly agentId: string; readonly version: number; readonly capabilityScopes: readonly string[] };
  readonly task: { readonly taskId: string; readonly status: TaskStatus };
  readonly context: TrustedActionContext;
  readonly capability: Pick<
    CapabilityDefinition,
    'capabilityId' | 'version' | 'riskClass' | 'requiredScopes' | 'identityRequirement' | 'confirmationPolicy' | 'approvalPolicy' | 'idempotency'
  > & {
    /** The declared recovery strategy of a registered write; null when the capability has no write handlers. */
    readonly writeRecovery: WriteRecoveryStrategy | null;
  };
}

export interface PolicyEvaluation {
  readonly outcome: PolicyOutcome;
  readonly reasonCode: string;
  /** Stable id of the rule that decided. */
  readonly rule: string;
  readonly message: string;
}

/** Deterministic authorization of governed actions (R4-D, ADR-017). */
export interface ActionAuthorizer {
  readonly identity: PolicyIdentity;
  evaluate(input: PolicyInput): PolicyEvaluation;
}

/**
 * What one external call established, as reported by the ActionExecutor to
 * the platform. Never more certain than the domain's own answer: a timeout,
 * a thrown error or output failing its schema is `unknown`.
 */
export interface ActionAttemptReport {
  readonly outcome: ActionAttemptOutcome;
  /** Why the outcome is unknown (timeout, handler_error, …), or the domain code of a rejection/failure. */
  readonly errorCode: string | null;
  readonly message: string | null;
  /** Schema-validated capability output (applied only). */
  readonly result: JsonValue | null;
  readonly resourceRef: string | null;
  readonly externalOperationRef: string | null;
  readonly executedAt: string | null;
  /** The domain reported that this call returned an effect applied earlier under the same key. */
  readonly replayed: boolean;
  readonly details: JsonValue | null;
  readonly durationMs: number;
}
